export type Lang = 'pt' | 'en';
const dict: Record<Lang, Record<Key, string>> = { en, pt };

interface I18n {
  lang: Lang;
  locale: string;
  setLang: (l: Lang) => void;
  t: (k: Key, params?: Record<string, string | number>) => string;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  const saved = storage.get<Lang>('lang');
  if (saved === 'pt' || saved === 'en') return saved;
  return navigator.language?.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    storage.set('lang', l);
  }, []);
  const value = useMemo<I18n>(
    () => ({
      lang,
      locale: lang === 'pt' ? 'pt-PT' : 'en-GB',
      setLang,
      // {nome} no texto é substituído pelo valor correspondente.
      t: (k, params) => {
        const text = dict[lang][k] ?? k;
        return params ? text.replace(/\{(\w+)\}/g, (m, p: string) => (p in params ? String(params[p]) : m)) : text;
      },
    }),
    [lang, setLang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside I18nProvider');
  return v;
}

